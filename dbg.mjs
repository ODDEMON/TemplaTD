import { JSDOM, VirtualConsole } from 'jsdom';
import fs from 'fs';
const html = fs.readFileSync('index.html', 'utf8');
const vc = new VirtualConsole();
vc.on('jsdomError', e => console.log('jsdomError:', e && e.message));
vc.on('error', e => console.log('error:', String(e)));
const dom = new JSDOM(html, { url: 'http://localhost/', runScripts: 'dangerously', virtualConsole: vc, beforeParse(w){ w.requestAnimationFrame=()=>0; w.cancelAnimationFrame=()=>{}; }});
const w = dom.window, doc = w.document;
const ORDER = []; const re = /<script src="([^"]+)"><\/script>/g; let mm;
while ((mm = re.exec(html))) ORDER.push(mm[1]);
for (const f of ORDER) w.eval(fs.readFileSync(f, 'utf8'));
await new Promise(r => { if (doc.readyState === 'complete') return r(); w.addEventListener('load', () => r()); setTimeout(r, 800); });
const BS = w.BS;
BS.i18n.setLang('zh');
BS.app.go('forge');
// click a card and a cell
const list = doc.getElementById('panel').querySelectorAll('[data-p]');
list[Math.floor(list.length/2)].dispatchEvent(new w.MouseEvent('click', {bubbles:true}));
const okCells = doc.getElementById('panel').querySelectorAll('.wgrid .cell.ok');
console.log('okCells:', okCells.length);
if (okCells.length) okCells[Math.floor(okCells.length/2)].dispatchEvent(new w.MouseEvent('click', {bubbles:true}));
console.log('shop n:', BS.shop.n());
doc.getElementById('panel').querySelector('[data-act="submit"]').dispatchEvent(new w.MouseEvent('click', {bubbles:true}));
console.log('armory:', JSON.stringify(BS.bus.state.armory.map(r=>({id:r.id, serial:r.serial, cost:r.cost, nm:r.spec.nm}))));
BS.app.go('battle');
BS.app.go('battle');
console.log('run:', !!BS.run.current());
const panelEl = doc.getElementById('panel');
console.log('has new btn:', !!panelEl.querySelector('[data-act="new"]'));
panelEl.querySelector('[data-act="new"]').dispatchEvent(new w.MouseEvent('click', {bubbles:true}));
console.log('run after new:', BS.run.current() && BS.run.current().phase, 'armory len:', BS.bus.state.armory.length);
console.log('panel txt:', doc.getElementById('panel').textContent.replace(/\s+/g,' ').slice(0,300));
console.log('pick btns:', doc.getElementById('panel').querySelectorAll('[data-act^="pick:"]').length);
