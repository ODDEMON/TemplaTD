/* core/cadence.js —— 投放的节律与偏置。
   ------------------------------------------------------------------
   这里没有一张你读得懂的速率表。上游落件的间隔、以及每一件的资质，
   是 n（已落序号）、seq（你动过的总次数）、以及若干无理数相位共同卷出来的
   一个准周期函数——周期长到你看不到尽头，任何一两个变量单独变化，
   都会以你无法反推的方式牵动全局。像一道不会给你答案的题：
   你只能观察它落下来，永远算不出来料什么时候、是什么。

   为什么这样写：如果节奏是常数，人一眼就看穿；如果节奏是随机，
   人一眼就知道是假随机。要让人「无论如何都不能理解」，
   唯一的办法是让它真的确定、真的光滑、真的没有短周期——
   于是它既不是常数，也不是噪声，而是一串看似无规律的必然。

   两个纯函数，都是确定性的（同一输入永远同一输出），所以存档与重算不受影响：
     · interval(n, seq)  第 n 件落件所需的秒数（速度，基准 = rig.PERIOD）
     · rarityShift(n, seq) 资质判定在 0..1 上的一个零均值扰动（概率）
   它们都不碰几何形状——同一序号永远是同一形状，这条铁律不动。 */
window.BS = window.BS || {};
(function (BS) {
  'use strict';

  /* 无理数倍频率：√2、√3、√5、黄金比，彼此的最小公倍数趋于无穷，
     于是叠加出来的节律没有可观测的短周期。 */
  var F = [
    Math.SQRT2 / 97,
    Math.sqrt(3) / 89,
    Math.sqrt(5) / 83,
    (1 + Math.sqrt(5)) / 2 / 71
  ];
  var P = [
    Math.sqrt(7) / 101,
    Math.sqrt(11) / 103,
    Math.sqrt(13) / 107,
    Math.E / 113
  ];

  /* 相位由 seq（动手次数）与 n 共同决定：同一个 n，动手多了，落件的节律就变了。 */
  function ph(n, seq) {
    var s = seq | 0, x = n | 0;
    return [x, x * 0.5 + s * 0.0137, s, x * s * 1e-4, (x + s) * 0.61803398875];
  }

  /* 把若干正弦/余弦/锯齿/二次项卷成一个零均值的标量，再压进 [-1,1]。 */
  function w0(n, seq) {
    var p = ph(n, seq), t = 0, i;
    for (i = 0; i < 4; i++) {
      t += Math.sin(p[0] * F[i] + p[1] * P[i]);
      t += Math.cos(p[1] * F[(i + 1) & 3] + p[2] * P[i]);
    }
    /* 锯齿：p[3] 的小数部分，二次项 p[4] 取模 2π */
    var saw = (p[3] - Math.floor(p[3])) - 0.5;
    t += saw * 2.0;
    t += Math.sin((p[4] * p[4]) % 6.283185307179586) * 1.3;
    /* 归一：8 项正弦余弦 + 锯齿(±0.5×2) + 二次项(±1.3)，理论上界约 8+1+1.3=10.3 */
    return t / 10.3;
  }

  /* interval：第 n 件落件所需秒数。
     基准 PERIOD 乘上一个被 w0 折叠的因子。fold 用「两个零均值正弦的乘积」
     再加一个小幅三角波，保证长期平均精确回到 1（无直流漂移），
     瞬时值则落在 [0.62, 1.38]×PERIOD 之间——永远猜不中下一拍。 */
  function interval(n, seq, PERIOD) {
    var w = w0(n, seq);
    var p = ph(n, seq);
    /* 纯交流项：sin·sin 与 sin·cos 的积都是零均值，均值不漂移 */
    var ac = Math.sin(w * 4.7) * Math.sin(p[0] * 0.37 + p[1] * 1.9);
    ac += Math.sin(w * 2.3 + p[2] * 0.19) * Math.cos(p[3] * 3.1 + p[4] * 0.71);
    ac *= 0.19;   /* 幅值 ±0.38 */
    var s = 1.0 + ac;   /* 0.62 .. 1.38，长期平均 = 1.0 */
    return (PERIOD || 15) * s;
  }

  /* rarityShift：资质判定的零均值扰动（落在 0..1 的 u 上加这个值再判定档位）。
     用另一个相位族，与 interval 正交，所以「快不快」与「稀不稀」互不泄露。 */
  function rarityShift(n, seq) {
    var p = ph(n, seq), t = 0, i;
    for (i = 0; i < 4; i++) {
      t += Math.sin(p[1] * F[i] + p[0] * P[(i + 2) & 3]);
      t -= Math.cos(p[2] * F[(i + 3) & 3] + p[0] * P[i]);
    }
    var saw = (p[4] - Math.floor(p[4])) - 0.5;
    t += saw * 1.5;
    t += Math.sin((p[3] * p[3]) % 6.283185307179586) * 1.1;
    return t / 10.3 * 0.08;   /* 零均值，幅值约 ±0.08：温和地把概率拨来拨去 */
  }

  BS.cadence = { interval: interval, rarityShift: rarityShift, w0: w0 };
})(window.BS);
